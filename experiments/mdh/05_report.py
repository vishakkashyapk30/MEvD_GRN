#!/usr/bin/env python
"""Compile the pre-registered tables and tests (README) into results/REPORT.md (+ CSVs).

  python 05_report.py [--n_boot 2000]
"""
from __future__ import annotations

import argparse
import json

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

import mdh_lib as L

MAIN_GTS = ["ChIP", "KO", "Union", "Intersection"]
NAMES = {"mid2_full": "MID-GRN v2", "mid2_marginal": "MID-GRN v2 marginal only", "mid2_full_g": "MID-GRN v2, interaction head only",
         "mid_full": "MID-GRN v1", "mid_full_g": "MID-GRN, interaction head only", "mid_dataonly": "MID-GRN, data-only",
         "mid_dataonly_g": "MID-GRN data-only, interaction head only", "mid_bce": "MID-GRN features, BCE loss",
         "mevd_fm_h384_hubmotif": "MeVD-GRN (M3)", "baseline_indegree": "In-degree (TF-disjoint)",
         "baseline_pearson": "Pearson", "baseline_grnboost2": "GRNBoost2"}


def nm(m):
    return NAMES.get(m, m)


def load_stats(ds, gt, method, seed):
    f = L.OUT / "stats" / ds / gt / f"{method}__{seed}.npz"
    return np.load(f) if f.exists() else None


def excess_boot(st_list, W):
    """st_list: npz per seed; W (B, R) TF weights -> (B,) mean over seeds of DR(real) - mean DR(null)."""
    out = []
    for z in st_list:
        def dr(C, N):
            return np.einsum("br,rk,bk->b", W, C, W) / np.maximum(np.einsum("br,rk,bk->b", W, N, W), 1e-12)
        real = dr(z["C"].astype(np.float64), z["N"].astype(np.float64))
        null = np.mean([dr(c.astype(np.float64), n.astype(np.float64)) for c, n in zip(z["Cn"], z["Nn"])], 0)
        out.append(real - null)
    return np.mean(out, 0)


def boot_compare(df_seeds, gt, a, b, n_boot, rng):
    """Across-dataset mean of [excess(a) - excess(b)], paired on seeds both have; TF-cluster bootstrap."""
    per_ds, boots = [], []
    for ds in L.DATASETS:
        sa = set(df_seeds.get((ds, gt, a), [])); sb = set(df_seeds.get((ds, gt, b), []))
        released_b = b in L.RELEASED or b in ("baseline_pearson", "baseline_grnboost2")
        seeds = sorted(sa) if released_b else sorted(sa & sb)
        if not seeds:
            continue
        za = [load_stats(ds, gt, a, s) for s in seeds]
        zb = [load_stats(ds, gt, b, s) for s in seeds]
        if any(z is None for z in za + zb):
            continue
        R = len(za[0]["rows"])
        W = np.vstack([np.ones(R), np.stack([np.bincount(rng.integers(0, R, R), minlength=R)
                                              for _ in range(n_boot)])]).astype(np.float64)
        d = excess_boot(za, W) - excess_boot(zb, W)
        per_ds.append((ds, d[0]))
        boots.append(d[1:])
    if not boots:
        return None
    pt = float(np.mean([x for _, x in per_ds]))
    bs = np.mean(np.stack(boots), 0)
    lo, hi = np.percentile(bs, [2.5, 97.5])
    p = float(min(1.0, 2 * min((bs <= 0).mean(), (bs >= 0).mean())))
    return {"gt": gt, "a": a, "b": b, "n_datasets": len(per_ds), "delta": pt, "lo": float(lo), "hi": float(hi),
            "p_boot": max(p, 1.0 / n_boot), "per_dataset": {k: round(float(v), 4) for k, v in per_ds}}


def holm(ps):
    order = np.argsort(ps)
    adj = np.empty(len(ps))
    run = 0.0
    for r, i in enumerate(order):
        run = max(run, (len(ps) - r) * ps[i])
        adj[i] = min(1.0, run)
    return adj


def fmt(x, nd=3):
    return "–" if x is None or (isinstance(x, float) and not np.isfinite(x)) else f"{x:.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n_boot", type=int, default=2000)
    args = ap.parse_args()
    rng = np.random.default_rng(0)
    lines = ["# MDH experiment: results", "",
             "Generated by `05_report.py` from `results/a2_metrics.csv`, `results/stats/`, `results/a1_gt_structure.csv` "
             "and the BEAR pooled score JSONs. Definitions: README.md (DR-AUROC and marginal null: deviation D1).", ""]
    a2 = pd.read_csv(L.OUT / "a2_metrics.csv")
    seeds = {k: sorted(g["seed"].unique()) for k, g in a2.groupby(["dataset", "gt", "method"])}

    # ---------------- A1
    a1 = pd.read_csv(L.OUT / "a1_gt_structure.csv")
    lines += ["## A1 (P1): marginal-only oracle vs methods, full-universe AUROC", "",
              "| Dataset | GT | TFs | positive rate | marginal oracle (LOO) | TF rate only | target rate only (LOO) | "
              "in-degree (TF-disjoint) | MeVD-GRN | best released (name) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for _, r in a1.iterrows():
        lines.append(f"| {r.dataset} | {r['gt']} | {r.n_tfs} | {r.pos_rate:.3f} | {r.marginal_oracle_loo:.3f} | "
                     f"{r.row_only:.3f} | {r.col_only_loo:.3f} | {fmt(r.get('indegree'))} | {fmt(r.get('MeVD-GRN'))} | "
                     f"{fmt(r.best_released)} ({r.best_released_name}) |")
    chip = a1[a1["gt"] == "ChIP"].dropna(subset=["best_released"])
    k = int((chip.marginal_oracle_loo >= chip.best_released).sum())
    lines += ["", f"**Criterion A1** (oracle ≥ best released on ≥ 7/9 ChIP datasets): {k}/{len(chip)} evaluable "
              f"(released networks are local only for {', '.join(chip.dataset)}) → "
              f"{'supported' if k >= 7 else 'not evaluable' if len(chip) < 7 else 'not supported'}.", ""]

    # ---------------- A2
    lines += ["## A2 (P2): pair-specific signal of published methods (DR-AUROC, same-fold pairs, mean over seed "
              "partitions)", "", "Cells: DR-AUROC / excess over marginal null.", ""]
    rel = a2[a2.method.isin(L.RELEASED)].groupby(["dataset", "gt", "method"])[["dr", "dr_excess"]].mean().reset_index()
    for gt in MAIN_GTS + ["Core"]:
        sub = rel[rel["gt"] == gt]
        if sub.empty:
            continue
        dss = [d for d in L.DATASETS if d in set(sub.dataset)]
        lines += [f"**{gt}**", "", "| Method | " + " | ".join(dss) + " |", "|---|" + "---|" * len(dss)]
        for m in L.RELEASED:
            cells = []
            for d in dss:
                q = sub[(sub.method == m) & (sub.dataset == d)]
                cells.append("–" if q.empty else f"{q.dr.iloc[0]:.3f} / {q.dr_excess.iloc[0]:+.3f}")
            lines.append(f"| {m} | " + " | ".join(cells) + " |")
        lines.append("")
    cr = rel[rel["gt"] == "ChIP"]
    ok = cr.groupby("dataset").dr.max() <= 0.55
    lines += [f"**Criterion A2** (every released method DR ≤ 0.55 on ChIP in ≥ 7/9 datasets): {int(ok.sum())}/{len(ok)}"
              f" → {'supported' if ok.sum() >= 7 else 'not supported'}. Max released DR on ChIP per dataset: "
              + ", ".join(f"{d} {v:.3f}" for d, v in cr.groupby('dataset').dr.max().items()), ""]

    # ---------------- A3
    a3f = L.OUT / "a3_summary.json"
    if a3f.exists():
        a3 = json.load(open(a3f))
        lines += ["## A3 (P7): ChIP vs Intersection AUROC across released methods", "",
                  f"Spearman ρ = {a3['spearman_rho_pooled']:.3f} (p = {a3['p']:.3g}, n = {a3['n']} method × dataset); "
                  "per dataset: " + ", ".join(f"{k} {v:.2f}" for k, v in a3["per_dataset_rho"].items())
                  + f". **Criterion A3** (ρ < 0): {'supported' if a3['spearman_rho_pooled'] < 0 else 'not supported'}.", ""]

    # ---------------- A4: model, DR excess
    methods = ["mid2_full", "mid2_marginal", "mid2_full_g", "mid_full", "mid_full_g", "mid_dataonly", "mid_dataonly_g", "mid_bce", "mevd_fm_h384_hubmotif",
               "baseline_indegree", "baseline_pearson", "baseline_grnboost2", "LINGER"]
    lines += ["## A4: pair-specific signal (DR-AUROC excess over the marginal null), mean over datasets and seeds", "",
              "| Method | " + " | ".join(MAIN_GTS) + " |", "|---|" + "---|" * len(MAIN_GTS)]
    agg = a2.groupby(["dataset", "gt", "method"])[["dr", "dr_excess", "rowm", "full"]].mean().reset_index()
    for m in methods:
        cells = []
        for gt in MAIN_GTS:
            q = agg[(agg.method == m) & (agg["gt"] == gt)]
            cells.append("–" if q.empty else f"{q.dr_excess.mean():+.4f} (DR {q.dr.mean():.3f}; n={len(q)})")
        lines.append(f"| {nm(m)} | " + " | ".join(cells) + " |")
    lines.append("")
    def family(a_, comps):
        ts = []
        for gt in MAIN_GTS:
            for b in comps:
                r = boot_compare(seeds, gt, a_, b, args.n_boot, rng)
                if r:
                    ts.append(r)
        if ts:
            for t, adj_ in zip(ts, holm([t["p_boot"] for t in ts])):
                t["p_holm"] = float(adj_)
        return ts
    tests = family("mid2_full", ["baseline_indegree", "mevd_fm_h384_hubmotif", "mid2_marginal"])
    tests_v1 = family("mid_full", ["baseline_indegree", "mevd_fm_h384_hubmotif"])
    extra = []
    for gt in MAIN_GTS:
        for a_, b_ in [("mid_full", "mid_bce"), ("mid_full", "mid_dataonly"), ("mid_full", "LINGER"),
                       ("mid_dataonly_g", "baseline_pearson")]:
            r = boot_compare(seeds, gt, a_, b_, args.n_boot, rng)
            if r:
                extra.append(r)
    lines += ["**v2 family** (post-hoc model, README v2; Holm over 3 comparators × 4 GTs) and **v1 family** (pre-registered; "
              "Holm over 2 × 4): Δ DR excess of the model minus comparator, mean over datasets, 95% TF-cluster bootstrap CI.", "",
              "| model | GT | comparator | datasets | Δ | 95% CI | p (bootstrap) | p (Holm) | significant |", "|---|---|---|---|---|---|---|---|---|"]
    for t in tests + tests_v1:
        lines.append(f"| {nm(t['a'])} | {t['gt']} | {nm(t['b'])} | {t['n_datasets']} | {t['delta']:+.4f} | [{t['lo']:+.4f}, {t['hi']:+.4f}] "
                     f"| {t['p_boot']:.3g} | {t['p_holm']:.3g} | {'yes' if t['p_holm'] < 0.05 and t['lo'] > 0 else 'no'} |")
    lines += ["", "**Secondary contrasts** (not in the Holm family):", "",
              "| GT | A | B | datasets | Δ (A − B) | 95% CI | p |", "|---|---|---|---|---|---|---|"]
    for t in extra:
        lines.append(f"| {t['gt']} | {nm(t['a'])} | {nm(t['b'])} | {t['n_datasets']} | {t['delta']:+.4f} | "
                     f"[{t['lo']:+.4f}, {t['hi']:+.4f}] | {t['p_boot']:.3g} |")
    lines.append("")
    json.dump({"v2": tests, "v1": tests_v1, "secondary": extra}, open(L.OUT / "a4_tests.json", "w"), indent=1)

    # ---------------- pooled BEAR metric
    def pooled(ds, method, gt, seeds_=None):
        base = L.ROOT / "results" / ds / "scores"
        if method in L.RELEASED or method == "baseline_coverage":
            f = base / (f"{method}__{gt}.json" if method in L.RELEASED else f"{method}__seed0__{gt}.json")
            return [json.load(open(f))] if f.exists() else []
        fs = sorted(base.glob(f"{method}__seed*__{gt}.json"))
        fs = [f for f in fs if f.name.count("__") == 2]
        if seeds_ is not None:
            fs = [f for f in fs if int(f.name.split("__")[1][4:]) in seeds_]
        return [json.load(open(f)) for f in fs]

    rows = []
    for ds in L.DATASETS:
        for gt in MAIN_GTS:
            if L.gt_full(ds, gt) is None:
                continue
            rec = {"dataset": ds, "gt": gt}
            for m in ["mid2_full", "mid2_marginal", "mid_full", "mid_dataonly", "mid_bce", "mevd_fm_h384_hubmotif", "baseline_indegree", "LINGER",
                      "baseline_coverage"] + [x for x in L.RELEASED if x != "LINGER"]:
                rs = pooled(ds, m, gt)
                if rs:
                    rec[f"{m}|AUROC"] = float(np.nanmean([r["AUROC"] for r in rs]))
                    rec[f"{m}|AUPRC"] = float(np.nanmean([r["AUPRC"] for r in rs]))
            rows.append(rec)
    pdf = pd.DataFrame(rows)
    pdf.to_csv(L.OUT / "pooled_bear.csv", index=False)
    lines += ["## BEAR pooled metrics (verified port; seed means)", ""]
    for metric in ["AUROC", "AUPRC"]:
        for gt in MAIN_GTS:
            sub = pdf[pdf["gt"] == gt]
            if sub.empty or f"mid2_full|{metric}" not in sub:
                continue
            lines += [f"**{gt} {metric}**", "", "| Dataset | MID-GRN v2 | v2 marginal only | MID-GRN v1 | MID v1 BCE | MeVD-GRN | in-degree | LINGER | best other released |",
                      "|---|---|---|---|---|---|---|---|---|"]
            for _, r in sub.iterrows():
                others = [r.get(f"{x}|{metric}") for x in L.RELEASED if x != "LINGER"]
                others = [o for o in others if o is not None and np.isfinite(o)]
                lines.append(f"| {r.dataset} | {fmt(r.get(f'mid2_full|{metric}'))} | {fmt(r.get(f'mid2_marginal|{metric}'))} | {fmt(r.get(f'mid_full|{metric}'))} | "
                             f"{fmt(r.get(f'mid_bce|{metric}'))} | {fmt(r.get(f'mevd_fm_h384_hubmotif|{metric}'))} | "
                             f"{fmt(r.get(f'baseline_indegree|{metric}'))} | {fmt(r.get(f'LINGER|{metric}'))} | "
                             f"{fmt(max(others) if others else None)} |")
            for b in ["baseline_indegree", "mid2_marginal", "mevd_fm_h384_hubmotif", "LINGER"]:
                if f"{b}|{metric}" not in sub:
                    continue
                pr = sub[[f"mid2_full|{metric}", f"{b}|{metric}"]].dropna()
                if len(pr) >= 2:
                    d = pr.iloc[:, 0] - pr.iloc[:, 1]
                    try:
                        pw = wilcoxon(d).pvalue if (d != 0).any() else 1.0
                    except ValueError:
                        pw = float("nan")
                    lines.append(f"- vs {nm(b)}: MID-GRN v2 higher on {int((d > 0).sum())}/{len(d)} datasets, mean Δ {d.mean():+.4f}, "
                                 f"Wilcoxon p = {pw:.3g}")
            lines.append("")
    # s12.9 rule: above LINGER, in-degree and coverage
    for mod, lab in [("mid2_full", "MID-GRN v2"), ("mid_full", "MID-GRN v1"), ("mevd_fm_h384_hubmotif", "MeVD-GRN (M3)")]:
        win = tot = 0
        for _, r in pdf.iterrows():
            for metric in ["AUROC", "AUPRC"]:
                v = r.get(f"{mod}|{metric}")
                refs = [r.get(f"{b}|{metric}") for b in ["LINGER", "baseline_indegree", "baseline_coverage"]]
                if v is None or not np.isfinite(v) or any(x is None or not np.isfinite(x) for x in refs):
                    continue
                tot += 1
                win += int(all(v > x for x in refs))
        lines += [f"**BEAR §12.9 win rule** (above LINGER, in-degree and coverage), {lab}: {win}/{tot} dataset × GT × metric cells.", ""]
    (L.OUT / "REPORT.md").write_text("\n".join(lines))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
